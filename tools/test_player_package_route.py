    def skip_if_toolchain_unavailable(self) -> None:
        required = ("mingw32-make", "gcc", "pwsh", "git")
        missing = [name for name in required if not shutil.which(name)]
        if missing:
            self.skipTest(
                "WINDOWS_ONLY: the player package route requires " + ", ".join(missing) + " on PATH"
            )
        # The package route links SDL3; a host without the supported toolchain
        # is a SKIP carrying the Makefile's own remedy, not a failed route.
        make_name = "mingw32-make" if os.name == "nt" else "make"
        probe = subprocess.run(
            [make_name, "--no-print-directory", "sdl3-check",
             f"BUILD_ROOT={self.binary_dir.as_posix()}"],
            cwd=ROOT, capture_output=True, text=True,
        )
        self.skip_if_toolchain_unusable(probe)
        for binary in (self.player, self.harness, self.validator):
            if not binary.is_file():
                built = subprocess.run(
                    [make_name, "--no-print-directory", "player", "player-state-test-bin",
                     "package-builder-test-bin", f"BUILD_ROOT={self.binary_dir.as_posix()}"],
                    cwd=ROOT, capture_output=True, text=True,
                )
                self.skip_if_toolchain_unusable(built)
                if not binary.is_file():
                    # The build's own last lines, so a run that must not skip (hosted CI's
                    # homebrew routes, NK_HOMEBREW_E2E_REQUIRED=1) says why it failed.
                    tail = "\n".join((built.stdout + built.stderr).splitlines()[-25:])
                    self.skipTest(f"the player package route needs {binary.name}; build failed "
                                  f"(exit {built.returncode}):\n{tail}")

    def require_homebrew_toolchain(self) -> None:
        """skip_if_toolchain_unavailable, but a failure under NK_HOMEBREW_E2E_REQUIRED=1.

        A required run (hosted CI's Windows routes) must run the route: a missing tool or a
        player that does not build fails it rather than skipping it (#2143).
        """
        try:
            self.skip_if_toolchain_unavailable()
        except unittest.SkipTest as skipped:
            if os.environ.get(HOMEBREW_REQUIRED) == "1":
                raise AssertionError(
                    f"{HOMEBREW_REQUIRED}=1, but the route cannot run: {skipped}"
                ) from skipped
            raise

    def skip_if_toolchain_unusable(self, run) -> None:
        output = run.stdout + run.stderr
        if run.returncode != 0 and "sdl3 dependency is missing" in output.lower():
            reason = next(line for line in output.splitlines()
                          if "sdl3 dependency is missing" in line.lower())
            self.skipTest(reason.strip())

    # ---- the two halves ------------------------------------------------------

    def run_build_action(self, user_root: Path, *, env=None) -> subprocess.CompletedProcess:
        """Press BUILD PACKAGE: the player's own session, start to finish."""
        built = subprocess.run(
            [str(self.harness), "--build-package", str(ROOT), str(user_root), DISC_ID,
             str(user_root / "logs")],
            cwd=ROOT, env=env, capture_output=True, text=True, timeout=1800,
        )
        return built

    def build_failure_message(
        self, built: subprocess.CompletedProcess, user_root: Path | None = None,
    ) -> str:
        """The assertion message for a build that had to pass: output, log tail, kept directory.

        Called where a test needs the build to succeed, so a non-zero exit there keeps the
        scratch directory. A refusal a test expects (an encrypted or malformed input) never
        calls it and is cleaned up like any other run.
        """
        if built.returncode != 0:
            self.keep_scratch = True
        return build_failure_report(
            built, (user_root or self.user_root) / "logs", DISC_ID,
            kept_scratch=Path(self.temporary.name) if self.keep_scratch else None,
        )

    def _remove_scratch(self) -> None:
        """Delete the scratch directory, except after a failed build: its logs are the evidence."""
        if self.keep_scratch:
            # Stop tempfile's finalizer too, or it would remove the directory at interpreter exit.
            finalizer = getattr(self.temporary, "_finalizer", None)
            if finalizer is not None:
                finalizer.detach()
            return
        self.temporary.cleanup()

    def run_validator(self) -> subprocess.CompletedProcess:
        return subprocess.run(
            [str(self.validator), "--validate-package", str(self.user_root), DISC_ID,
             TITLE_ID, "1", "EBOOT.BIN"],
            cwd=ROOT, capture_output=True, text=True,
        )

    @staticmethod
    def _load_span(executable: bytes) -> tuple[int, int]:
        phoff = struct.unpack_from("<I", executable, 28)[0]
        phentsize = struct.unpack_from("<H", executable, 42)[0]
        phnum = struct.unpack_from("<H", executable, 44)[0]
        spans = []
        for index in range(phnum):
            header_offset = phoff + index * phentsize
            p_type, _p_offset, p_vaddr, _paddr, _filesz, p_memsz = struct.unpack_from(
                "<6I", executable, header_offset
            )
            if p_type == 1 and p_memsz:
                spans.append((p_vaddr, p_vaddr + p_memsz))
        return min(start for start, _end in spans), max(end for _start, end in spans)

    def run_launch(
        self, perf_csv: Path, *, accept_presented_frames: int | None = None,
        headless_timeout_ms: int | None = None, user_data_root: Path | None = None,
        extra_environment: dict[str, str] | None = None,
    ) -> subprocess.CompletedProcess:
        environment = os.environ.copy()
        environment["LOCALAPPDATA"] = str(self.local_appdata)
        environment.update(extra_environment or {})
        # The acceptance route must exercise a real host presenter. A caller's
        # offscreen SDL selection would make the test prove only framebuffer
        # conversion, so clear those overrides for this windowed child.
        environment.pop("SR_VIDEO", None)
        environment.pop("SDL_VIDEODRIVER", None)
        environment.pop("SDL_VIDEO_DRIVER", None)
        # The same presenter with its window hidden (SR_WINDOW_HIDDEN, sdl3vk.c):
        # nobody watches this run. Shown, the child's window joined the taskbar
        # group of any Nakagawa player open on the PC as a blank "Nakagawa
        # Recomp" window for the length of the launch.
        environment["SR_WINDOW_HIDDEN"] = "1"
        # The opt-in child evidence channels. SR_PERF_CSV is how a launcher
        # proves the guest consumed vblanks without reading the child's stderr,
        # which is not a stable API of either process backend.
        environment["SR_PERF"] = "1"
        environment["SR_PERF_CSV"] = str(perf_csv)
        ucrt_bin = Path("C:/msys64/ucrt64/bin")
        if os.name == "nt" and ucrt_bin.is_dir():
            environment["PATH"] = str(ucrt_bin) + os.pathsep + environment.get("PATH", "")
        arguments = [
            str(self.player), "--empty", "--launch-index=0", "--headless-launch",
            f"--runtime-root={user_data_root or self.user_root}",
        ]
