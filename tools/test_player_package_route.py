"""The v0.0.1 player package route on a source-owned fixture (#509).

A consumer's whole route is: add an ISO, press BUILD PACKAGE, press PLAY. Every
other gate proves one of those halves on its own. This one drives both halves
the way the player does, on a source-owned fixture, with no mocked compilation:

  * the build half runs ``package_builder_start`` -- the player's own BUILD
    PACKAGE action, which spawns ``tools/nk_cli.py build-package`` and reads its
    progress stream -- against real analysis, real AOT codegen and a real
    ``gcc``/``mingw32-make`` link of the display/presentation fixture;
  * the package is then checked with the player's own validator
    (``player_app_validate_runtime_package``);
  * the launch half runs the player executable's ``--launch-index`` route with
    ``--headless-launch``, the headless sibling of PLAY NOW, so a host with no
    display still reaches ``player_app_launch_game`` -> ``nk_launch_start`` and
    the guest actually runs;
  * two missing-prerequisite boundaries must arrive as the player's named,
    structured failures instead of a silent package;
  * the whole route must leave every repository-tracked file untouched.

The fixture is the source-owned display smoke guest generated by
``fixtures/display_smoke/generate.py``: hand-assembled MIPS from a committed
recipe, no PSPDEV toolchain, no retail bytes. It is the only public-scope title
the native player can launch, so it is the one fixture that can carry this
route. A host without the documented toolchain is a SKIP with the Makefile's own
remedy, never a silent pass.
"""

