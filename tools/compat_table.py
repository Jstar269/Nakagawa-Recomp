"""The public whole-library compatibility summary, from a private library build.

    python tools/compat_table.py <library-build.json> [--release-plan release-plan.json]
        [--write-doc docs/COMPATIBILITY.md]
        [--output summary.md] [--json summary.json] [--date YYYY-MM-DD]

``tools/library_build.py`` builds every disc in a folder and records each one (private: it
names the user's discs). This tool turns that record into counts only: how many discs reach
each tier, split by disc verification, and where they stop, by named cause and the issue that
owns it. No title, disc ID, file name, hash or path reaches the output, and the tool refuses to
write a summary in which any string from the input's identifying fields appears.

Tiers, in order (``docs/COMPATIBILITY.md`` explains them):

- does not build: the build failed, timed out or left no report;
- builds, no frame: built, but its first launch submitted no frame;
- draws frames: its first launch submitted at least one frame;
- reaches menus, reaches gameplay, playable start to end: decided by scripted-input checks,
  which the library build does not run yet, so they are shown as not measured.

Discs without a current package in the run (not built yet or replaced by a later same-ID build),
and copies of an image already counted, are left out and counted below the table. The summary
names the run's settings (time budget, launch timeout, source commit) so two summaries are compared
like for like.

For a release, prepare the separate private plan from the approved input corpus before the sweep.
Use JSON with format ``nakagawa-compat-release-plan``, schema_version 1, a settings object
(``source_commit`` as the full lowercase commit, ``title_timeout_seconds``,
``launch_timeout_seconds`` and boolean ``decrypt``), and a nonempty ``sources`` array. Each entry
has the builder's exact relative ``source`` spelling, whole-image ``size_bytes`` and lowercase
``sha1``. A builder verification pass with ``--verify-only`` can record whole-image hashes before
a build. The exporter compares recorded identities and never opens the disc images. Keep the
plan private. Without ``--release-plan``, historical and partial reports remain available.
"""

from __future__ import annotations

import argparse
from collections import Counter
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import sys
from typing import Any, Iterable, cast

TOOLS = Path(__file__).resolve().parent
if str(TOOLS) not in sys.path:
    sys.path.insert(0, str(TOOLS))

from nk_core import disc_verify  # noqa: E402

ROOT = TOOLS.parent
FAILURE_CODES = ROOT / "assets" / "failure_codes.json"
MANIFEST_FORMAT = "nakagawa-library-build"
RELEASE_PLAN_FORMAT = "nakagawa-compat-release-plan"
DOC_BEGIN = "<!-- compat-table:begin (generated by tools/compat_table.py; do not edit) -->"
DOC_END = "<!-- compat-table:end -->"
ISSUE_URL = "https://github.com/Jstar269/nakagawa-recomp/issues/{}"

NOT_BUILT = "NOT_BUILT"
NO_FRAME = "NO_FRAME"
DRAWS_FRAMES = "DRAWS_FRAMES"
REACHES_MENUS = "REACHES_MENUS"
REACHES_GAMEPLAY = "REACHES_GAMEPLAY"
PLAYABLE = "PLAYABLE"
TIERS = (NOT_BUILT, NO_FRAME, DRAWS_FRAMES, REACHES_MENUS, REACHES_GAMEPLAY, PLAYABLE)
MEASURED_TIERS = (NOT_BUILT, NO_FRAME, DRAWS_FRAMES)
TIER_LABELS = {
    NOT_BUILT: "Does not build",
    NO_FRAME: "Builds, no frame in its first launch",
    DRAWS_FRAMES: "Draws frames",
    REACHES_MENUS: "Reaches menus",
    REACHES_GAMEPLAY: "Reaches gameplay",
    PLAYABLE: "Playable start to end",
}
VERIFICATION_COLUMNS = (disc_verify.VERIFIED_RETAIL, disc_verify.MODIFIED, disc_verify.UNKNOWN,
                        disc_verify.NOT_CHECKED)
VERIFICATION_LABELS = {
    disc_verify.VERIFIED_RETAIL: "Verified retail",
    disc_verify.MODIFIED: "Modified",
    disc_verify.UNKNOWN: "Unknown",
    disc_verify.NOT_CHECKED: "Not checked",
}
BUILD_FAILURES = frozenset({"BUILD_FAILED", "TIMED_OUT", "NO_REPORT"})
NOT_RUN_YET = frozenset({"PENDING", "RUNNING"})
# The issue that owns each named cause. A cause not listed belongs to the end-to-end
# ISO-to-play work (#308); compile memory and time belong to the bounded-compile work, and
# instructions the generated code does not cover to the VFPU coverage work.
CAUSE_ISSUES = {"COMPILE_FAILED": 1730, "TITLE_TIME_BUDGET": 1730, "UNSUPPORTED_INSTRUCTION": 326}
DEFAULT_CAUSE_ISSUE = 308
# A cause name outside the failure-code taxonomy is never printed: it is counted as this.
OTHER_CAUSE = "OTHER"
NO_CAUSE = "NONE"
# Plain words beside the causes a reader would otherwise misread.
CAUSE_NOTES = {
    "LAUNCH_TIMEOUT": "still running when its first launch ended",
}
# A datafile version is published only in one of these shapes (Redump's is a date and time);
# anything else in that free-text field is left out.
_DATAFILE_VERSION = re.compile(
    r"[0-9]{4}-[0-9]{2}-[0-9]{2}(?: [0-9]{2}[-:][0-9]{2}[-:][0-9]{2})?|[0-9]+(?:\.[0-9]+){0,3}")
# Text that looks like a private identifier: a disc ID, a SHA-1 or a host path.
_IDENTIFIER_SHAPES = (
    re.compile(r"\b[A-Z]{4}-?[0-9]{5}\b"),
    re.compile(r"\b[0-9a-fA-F]{40}\b"),
    re.compile(r"(?<![A-Za-z])[A-Za-z]:[\\/]|\\\\"),
)


class PrivacyError(ValueError):
    """The summary would carry something from the input's identifying fields."""


def load_codes(path: Path = FAILURE_CODES) -> frozenset[str]:
    """The failure-code taxonomy's names: the only cause names a summary prints."""
    payload = json.loads(path.read_text(encoding="utf-8"))
    return frozenset(payload["codes"]) | {NO_CAUSE}


def _launch(record: dict[str, Any]) -> dict[str, Any]:
    launch = record.get("launch")
    return launch if isinstance(launch, dict) else {}


def tier_of(record: dict[str, Any]) -> str | None:
    """A disc's tier, or None when it has no current package or is a copy."""
    outcome = record.get("outcome")
    if outcome in BUILD_FAILURES:
        return NOT_BUILT
    if outcome != "BUILT":
        return None
    frames = _launch(record).get("frame_submissions")
    if _launch(record).get("presentation") == "FRAME_SUBMITTED" or (
            type(frames) is int and frames > 0):
        return DRAWS_FRAMES
    return NO_FRAME


def cause_of(record: dict[str, Any], codes: frozenset[str]) -> str:
    """The named cause a disc stopped at: a failure-code name, or OTHER."""
    if record.get("outcome") == "BUILT":
        value = _launch(record).get("failure_class") or record.get("failure_class")
    else:
        value = record.get("failure_class") or record.get("identify_error")
    if not isinstance(value, str) or not value:
        return NO_CAUSE
    return value if value in codes else OTHER_CAUSE


def verification_of(record: dict[str, Any]) -> str:
    tier = (record.get("verification") or {}).get("tier") if isinstance(
        record.get("verification"), dict) else None
    return cast(str, tier) if tier in VERIFICATION_COLUMNS else disc_verify.NOT_CHECKED


def _seconds(value: Any) -> int | None:
    return value if type(value) is int and value > 0 else None


def _settings_key(settings: Any) -> tuple:
    """Normalize recorded build settings; a value of another shape counts as unrecorded."""
    if not isinstance(settings, dict):
        return (None, None, None, None)
    commit = settings.get("source_commit")
    decrypt = settings.get("decrypt")
    return (_seconds(settings.get("title_timeout_seconds")),
            _seconds(settings.get("launch_timeout_seconds")),
            commit if isinstance(commit, str) and re.fullmatch(r"[0-9a-f]{40}", commit) else None,
            decrypt if type(decrypt) is bool else None)


def summarize(manifest: dict[str, Any], codes: frozenset[str] | None = None) -> dict[str, Any]:
    """The aggregate: counts only, every key and value from a fixed vocabulary or a number."""
    if not isinstance(manifest, dict) or manifest.get("format") != MANIFEST_FORMAT:
        raise ValueError("not a library-build manifest")
    titles = manifest.get("titles")
    if not isinstance(titles, list):
        raise ValueError("the manifest has no titles list")
    codes = load_codes() if codes is None else codes
    grid: Counter = Counter()
    causes: Counter = Counter()
    left_out: Counter = Counter()
    settings: Counter = Counter()
    for record in titles:
        if not isinstance(record, dict):
            continue
        tier = tier_of(record)
        if tier is None:
            left_out["copies" if record.get("outcome") == "DUPLICATE" else "not_built_yet"] += 1
            continue
        grid[(tier, verification_of(record))] += 1
        causes[(tier, cause_of(record, codes))] += 1
        settings[_settings_key(record.get("run_settings"))] += 1
    datafile = (cast(dict[str, Any], manifest.get("datafile"))
                if isinstance(manifest.get("datafile"), dict) else {})
    version = datafile.get("version")
    return {
        "format": "nakagawa-compat-summary",
        "schema_version": 1,
        "counted": sum(grid.values()),
        "tiers": {tier: {column: grid[(tier, column)] for column in VERIFICATION_COLUMNS}
                  for tier in MEASURED_TIERS},
        "causes": [
            {"tier": tier, "cause": cause, "discs": count,
             "issue": CAUSE_ISSUES.get(cause, DEFAULT_CAUSE_ISSUE)}
            for (tier, cause), count in sorted(causes.items(),
                                               key=lambda item: (TIERS.index(item[0][0]),
                                                                 -item[1], item[0][1]))
        ],
        "left_out": {"not_built_yet": left_out["not_built_yet"], "copies": left_out["copies"]},
        "settings": [
            # A short commit: a whole one has the shape of an image's SHA-1, which never
            # leaves the tool.
            {"title_timeout_seconds": key[0], "launch_timeout_seconds": key[1],
             "source_commit": key[2][:12] if key[2] else None, "decrypt": key[3],
             "discs": count}
            for key, count in sorted(settings.items(), key=lambda item: -item[1])
        ],
        "datafile": {
            "version": version if isinstance(version, str) and _DATAFILE_VERSION.fullmatch(version)
            else None,
            "discs": datafile.get("discs") if type(datafile.get("discs")) is int else None,
            "serials": datafile.get("serials") if type(datafile.get("serials")) is int else None,
        },
    }


def _number(value: int) -> str:
    return f"{value:,}"


def _settings_sentence(settings: list[dict[str, Any]]) -> str:
    if not settings:
        return "No disc was counted."
    parts = []
    for row in settings:
        budget = (f"a {row['title_timeout_seconds']} s time budget per disc"
                  if type(row["title_timeout_seconds"]) is int else "an unrecorded time budget")
        launch = (f"a {row['launch_timeout_seconds']} s first launch"
                  if type(row["launch_timeout_seconds"]) is int else "an unrecorded launch time")
        commit = (f"commit `{row['source_commit']}`" if row["source_commit"]
                  else "an unrecorded commit")
        # Whether the build decrypted the disc's own program; an older run didn't say.
        decrypt = {True: ", decrypting each disc's program",
                   False: ", without decrypting"}.get(cast(bool, row.get("decrypt")), "")
        parts.append(f"{_number(row['discs'])} built from {commit}, with {budget} and {launch}"
                     f"{decrypt}")
    sentence = "; ".join(parts) + "."
    if len(settings) > 1:
        sentence += (" These discs were not all built with the same settings, so compare this "
                     "summary with another only row by row of the same settings.")
    return sentence[0].upper() + sentence[1:]


def render_markdown(summary: dict[str, Any], date: str) -> str:
    """The summary as the block docs/COMPATIBILITY.md carries between its markers."""
    tiers = summary["tiers"]
    lines = [
        DOC_BEGIN,
        "",
        f"Whole library, {date}: {_number(summary['counted'])} disc images counted. "
        + _settings_sentence(summary["settings"]),
        "`tools/library_build.py` gives each disc one hidden first launch with no input.",
        "",
    ]
    datafile = summary["datafile"]
    if datafile.get("discs"):
        lines += [
            f"Disc verification compared each whole image with a Redump PSP list "
            f"({_number(datafile['discs'])} discs, version {datafile.get('version') or 'unknown'}).",
        ]
        if not datafile.get("serials"):
            lines += [
                "That list names no disc IDs, so an image counts as **Modified** only when its retail "
                "disc is verified in the same library. A lone fan translation counts as **Unknown**: "
                "unknown means not shown to be retail, not modified.",
            ]
        lines += [""]
    else:
        lines += ["No Redump list was found for this run (neither the bundled list nor an import), "
                  "so every disc is **Not checked**.", ""]
    header = "| Tier | " + " | ".join(VERIFICATION_LABELS[column] for column in VERIFICATION_COLUMNS)
    lines += ["The **Verified retail** column is the library's compatibility; modified and unknown "
              "images are counted beside it, apart.", ""]
    lines += [header + " | All |", "| :--- |" + " ---: |" * (len(VERIFICATION_COLUMNS) + 1)]
    for tier in TIERS:
        if tier in tiers:
            row = tiers[tier]
            cells = [_number(row[column]) for column in VERIFICATION_COLUMNS]
            cells.append(_number(sum(row.values())))
        else:
            cells = ["not measured"] * (len(VERIFICATION_COLUMNS) + 1)
        lines.append(f"| {TIER_LABELS[tier]} | " + " | ".join(cells) + " |")
    totals = [_number(sum(tiers[tier][column] for tier in tiers)) for column in VERIFICATION_COLUMNS]
    lines.append("| **Counted** | " + " | ".join(totals) + f" | {_number(summary['counted'])} |")
    left_out = summary["left_out"]
    copies = ("copy of a disc" if left_out["copies"] == 1 else "copies of a disc")
    lines += [
        "",
        f"Not counted: {_number(left_out['not_built_yet'])} without a current package in this run "
        "(not built yet or replaced by a later same-ID build), and "
        f"{_number(left_out['copies'])} {copies} already counted.",
        "",
        "Where they stop, by named cause ([`FAILURE_CODES.md`](FAILURE_CODES.md)):",
        "",
        "| Tier | Cause | Discs | Issue |",
        "| :--- | :--- | ---: | :--- |",
    ]
    for row in summary["causes"]:
        cause = row["cause"]
        name = {NO_CAUSE: "none named", OTHER_CAUSE: "other"}.get(cause, f"`{cause}`")
        if cause in CAUSE_NOTES:
            name += f" ({CAUSE_NOTES[cause]})"
        issue = f"[#{row['issue']}]({ISSUE_URL.format(row['issue'])})"
        lines.append(f"| {TIER_LABELS[row['tier']]} | {name} | {_number(row['discs'])} | {issue} |")
    lines += ["", DOC_END]
    return "\n".join(lines) + "\n"


def identifiers(manifest: dict[str, Any]) -> set[str]:
    """Every string in the input that names a disc, a file or a place on the user's machine."""
    found: set[str] = set()
    fields = ("disc_id", "title", "source", "source_key", "work_dir", "duplicate_of",
              "identify_detail")

    def add(value: Any) -> None:
        if isinstance(value, str) and len(value.strip()) >= 4:
            found.add(value.strip())

    for key in ("disc_root", "user_data_root"):
        add(manifest.get(key))
    for record in manifest.get("titles") or []:
        if not isinstance(record, dict):
            continue
        for key in fields:
            add(record.get(key))
        source = record.get("source")
        if isinstance(source, str):
            for part in re.split(r"[\\/]", source):
                add(part)
                add(Path(part).stem)
        verification = record.get("verification")
        if isinstance(verification, dict):
            for key in ("sha1", "crc32", "redump_name"):
                add(verification.get(key))
    return found


def _words(text: str) -> set[str]:
    return set(re.findall(r"[0-9a-z]+", text.casefold()))


def template_words() -> frozenset[str]:
    """Every word the summary's own text can hold, whatever the data: its sentences, labels
    and cause names. A folder or disc named only with these words ("Modified", "Library")
    does not identify anything when they appear."""
    codes = load_codes()
    sample = {
        "format": MANIFEST_FORMAT, "datafile": {"version": "1", "discs": 1, "serials": 0},
        "titles": [
            {"outcome": outcome, "failure_class": cause, "launch": {"frame_submissions": frames,
                                                                    "failure_class": cause},
             "run_settings": settings, "verification": {"tier": tier}}
            for outcome, frames in (("BUILT", 1), ("BUILT", 0), ("BUILD_FAILED", 0))
            for cause in ("LAUNCH_TIMEOUT", "NOT_A_CODE", None)
            for settings in ({}, {"title_timeout_seconds": 1, "launch_timeout_seconds": 1,
                                  "source_commit": "0" * 40})
            for tier in VERIFICATION_COLUMNS
        ] + [{"outcome": "PENDING"}, {"outcome": "DUPLICATE"}],
    }
    summary = summarize(sample, codes)
    text = render_markdown(summary, "2000-01-01") + json.dumps(summary)
    text += " ".join(code.replace("_", " ") for code in codes)
    no_list = dict(summary, datafile={"version": None, "discs": None, "serials": None})
    text += render_markdown(no_list, "2000-01-01")
    return frozenset(_words(text))


def check_public(text: str, manifest: dict[str, Any]) -> None:
    """Refuse a summary that carries any identifier of the input, or anything shaped like one."""
    # Whole words only: a disc named like part of a cause name ("EXIT" in EXITED_...) is not
    # in the summary, but the same word standing alone would be. A name made only of the
    # summary's own words can appear without coming from the data.
    folded = text.casefold()
    vocabulary = template_words()
    leaked = sorted(
        value for value in identifiers(manifest)
        if value.casefold() in folded and not _words(value) <= vocabulary and re.search(
            r"(?<![0-9a-z])" + re.escape(value.casefold()) + r"(?![0-9a-z])", folded)
    )
    if leaked:
        raise PrivacyError(f"the summary would carry {len(leaked)} private identifier(s)")
    for shape in _IDENTIFIER_SHAPES:
        if shape.search(text):
            raise PrivacyError("the summary holds text shaped like a disc ID, hash or path")


def replace_doc_block(document: str, block: str) -> str:
    """docs/COMPATIBILITY.md with the text between its markers replaced by block."""
    start = document.find(DOC_BEGIN)
    end = document.find(DOC_END)
    if start < 0 or end < start:
        raise ValueError("the document has no compat-table markers")
    return document[:start] + block.rstrip("\n") + document[end + len(DOC_END):]


def _release_sources(plan: Any) -> tuple[tuple, dict[str, tuple[int, str]]]:
    if (not isinstance(plan, dict) or plan.get("format") != RELEASE_PLAN_FORMAT
            or type(plan.get("schema_version")) is not int or plan["schema_version"] != 1):
        raise ValueError("release plan is not a supported compatibility release plan")
    settings = _settings_key(plan.get("settings"))
    if None in settings:
        raise ValueError("release plan settings are incomplete or invalid")
    sources: dict[str, tuple[int, str]] = {}
    planned = plan.get("sources")
    if not isinstance(planned, list) or not planned:
        raise ValueError("release plan must name its expected corpus")
    for item in planned:
        if not isinstance(item, dict):
            raise ValueError("release plan has an invalid corpus entry")
        source, size, digest = item.get("source"), item.get("size_bytes"), item.get("sha1")
        if (not isinstance(source, str) or not source or source in sources
                or type(size) is not int or size < 0 or not isinstance(digest, str)
                or re.fullmatch(r"[0-9a-f]{40}", digest) is None):
            raise ValueError("release plan has an invalid or repeated corpus entry")
        sources[source] = (size, digest)
    return settings, sources


def _validate_release_dispositions(rows: dict[str, dict[str, Any]],
                                   sources: dict[str, tuple[int, str]]) -> None:
    replacements: dict[str, str] = {}
    for source, row in rows.items():
        outcome = row.get("outcome")
        if outcome not in ("DUPLICATE", "REPLACED"):
            continue
        field = "duplicate_of" if outcome == "DUPLICATE" else "replaced_by"
        reference = row.get(field)
        if not isinstance(reference, str) or reference == source or reference not in rows:
            raise ValueError("release corpus has an invalid copy or replacement reference")
        witness = rows[reference]
        disc_id = row.get("disc_id")
        if not isinstance(disc_id, str) or not disc_id or disc_id != witness.get("disc_id"):
            raise ValueError("release corpus copy or replacement has a different disc ID")
        same_content = sources[source] == sources[reference]
        if outcome == "DUPLICATE":
            if not same_content or witness.get("outcome") == "DUPLICATE":
                raise ValueError("release corpus copy does not match its counted source")
        else:
            if same_content or witness.get("outcome") not in ("BUILT", "REPLACED"):
                raise ValueError("release corpus replacement does not name a different built variant")
            replacements[source] = reference

    resolved: set[str] = set()
    for source in replacements:
        chain: set[str] = set()
        while source in replacements and source not in resolved:
            if source in chain:
                raise ValueError("release corpus replacement references form a cycle")
            chain.add(source)
            source = replacements[source]
        resolved.update(chain)


def validate_release(manifest: Any, plan: Any) -> None:
    """Refuse an incomplete or mismatched release export before rendering or writing."""
    settings, sources = _release_sources(plan)
    if (not isinstance(manifest, dict) or manifest.get("format") != MANIFEST_FORMAT
            or type(manifest.get("schema_version")) is not int or manifest["schema_version"] != 1):
        raise ValueError("release input is not a supported library-build manifest")
    if _settings_key(manifest.get("settings")) != settings:
        raise ValueError("release manifest settings differ from the plan")
    titles = manifest.get("titles")
    if not isinstance(titles, list):
        raise ValueError("release corpus membership differs from the plan")
    rows: dict[str, dict[str, Any]] = {}
    for row in titles:
        source = row.get("source") if isinstance(row, dict) else None
        if not isinstance(source, str) or source not in sources or source in rows:
            raise ValueError("release corpus membership differs from the plan")
        rows[source] = row
    if rows.keys() != sources.keys():
        raise ValueError("release corpus membership differs from the plan")

    terminal = BUILD_FAILURES | {"BUILT", "DUPLICATE", "REPLACED"}
    for source, row in rows.items():
        outcome = row.get("outcome")
        if not isinstance(outcome, str) or outcome not in terminal:
            raise ValueError("release corpus has unfinished or unknown outcomes")
        if outcome != "DUPLICATE" and _settings_key(row.get("run_settings")) != settings:
            raise ValueError("release row settings differ from the plan")
        verification = row.get("verification")
        size = row.get("size_bytes")
        if (not isinstance(verification, dict) or type(size) is not int or size < 0
                or type(verification.get("size_bytes")) is not int
                or verification["size_bytes"] != size):
            raise ValueError("release corpus identity is unverified")
        digest = verification.get("sha1")
        if not isinstance(digest, str) or re.fullmatch(r"[0-9a-f]{40}", digest) is None:
            raise ValueError("release corpus identity is unverified")
        if (size, digest) != sources[source]:
            raise ValueError("release corpus identity differs from the plan")
    _validate_release_dispositions(rows, sources)


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("manifest", type=Path, help="A library-build.json (private)")
    parser.add_argument("--release-plan", type=Path, default=None,
                        help="Require candidate settings and the expected private corpus before exporting")
    parser.add_argument("--write-doc", type=Path, default=None,
                        help="Replace the generated block in this document (docs/COMPATIBILITY.md)")
    parser.add_argument("--output", type=Path, default=None, help="Write the block to this file")
    parser.add_argument("--json", type=Path, default=None, help="Write the counts as JSON")
    parser.add_argument("--date", default=None,
                        help="The date the summary names (default: the manifest's last update)")
    args = parser.parse_args(list(argv) if argv is not None else None)
    outputs = [path for path in (args.write_doc, args.output, args.json) if path is not None]

    def same_file(first: Path, second: Path) -> bool:
        # Two names of one file (the same path, or a hard link) are one file.
        if first.resolve() == second.resolve():
            return True
        try:
            return first.exists() and second.exists() and os.path.samefile(first, second)
        except OSError:
            return False

    inputs = [args.manifest]
    if args.release_plan is not None:
        if same_file(args.manifest, args.release_plan):
            parser.error("the release plan must be separate from its manifest")
        inputs.append(args.release_plan)
    if any(same_file(path, source) for path in outputs for source in inputs) or any(
            same_file(first, second) for index, first in enumerate(outputs)
            for second in outputs[index + 1:]):
        parser.error("each output must be a file of its own, separate from the inputs")
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    if args.release_plan is not None:
        try:
            plan = json.loads(args.release_plan.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            parser.error("cannot read the private release plan")
        try:
            validate_release(manifest, plan)
        except ValueError as error:
            parser.error(str(error))
    summary = summarize(manifest)
    updated = manifest.get("updated_at")
    date = args.date or (updated[:10] if isinstance(updated, str) and len(updated) >= 10
                         else datetime.now(timezone.utc).strftime("%Y-%m-%d"))
    if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", date):
        parser.error("--date must be YYYY-MM-DD")
    block = render_markdown(summary, date)
    payload = json.dumps(summary, indent=1, sort_keys=True) + "\n"
    check_public(block, manifest)
    check_public(payload, manifest)
    if args.write_doc is not None:
        document = args.write_doc.read_text(encoding="utf-8")
        args.write_doc.write_text(replace_doc_block(document, block), encoding="utf-8",
                                  newline="\n")
    if args.output is not None:
        args.output.write_text(block, encoding="utf-8", newline="\n")
    if args.json is not None:
        args.json.write_text(payload, encoding="utf-8", newline="\n")
    if args.write_doc is None and args.output is None and args.json is None:
        sys.stdout.write(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
