"""Write the launcher's Love All credits table, ``src/player/ui/love_all_credits.c``, from CREDITS.md.

CREDITS.md stays the one source of truth: the launcher's Love All screen scrolls the table
this script derives from it. Every ``## `` section becomes a heading and every ``- **...**``
bullet under it an entry: the bold words name the project (and, after an em dash inside
them, who made it); a bold name alone takes the words after it, up to the next em dash, as
who made it when the bullet has one. Links, code spans and emphasis are reduced to their
text. The sentence that names the dedication becomes the closing line. The output is
deterministic and ASCII (other bytes are octal escapes).

    python tools/gen_credits_table.py           # rewrite src/player/ui/love_all_credits.c
    python tools/gen_credits_table.py --out F   # write elsewhere
    python tools/gen_credits_table.py --check   # exit 1 when the committed file is stale

``python tools/regen_all.py`` runs this step with the other generators.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path("CREDITS.md")
OUTPUT = Path("src/player/ui/love_all_credits.c")
EM_DASH = " — "
MAX_PEOPLE = 80  # a longer clause after a bold name is a description, not who made it

HEADING = "LOVE_ALL_HEADING"
ENTRY = "LOVE_ALL_ENTRY"
DEDICATION = "LOVE_ALL_DEDICATION"

_LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")
_AUTOLINK = re.compile(r"<(https?://[^>]*)>")
_BOLD = re.compile(r"\*\*(.+?)\*\*")
_DEDICATION = re.compile(r"(dedicated to [^;.]+)", re.IGNORECASE)


def plain(text: str) -> str:
    """Markdown inline text as the words a reader sees."""
    text = _LINK.sub(r"\1", text)
    text = _AUTOLINK.sub(r"\1", text)
    text = text.replace("**", "").replace("`", "")
    return " ".join(text.split())


def parse(markdown: str) -> list[tuple[str, str, str | None]]:
    """(kind, name, people) rows in CREDITS.md order."""
    rows: list[tuple[str, str, str | None]] = []
    bullets: list[str] = []
    dedication: str | None = None

    def entry(match: re.Match[str], bullet: str) -> None:
        bold = plain(match.group(1))
        rest = bullet[match.end():]
        people: str | None = None
        if EM_DASH in bold:
            bold, people = bold.split(EM_DASH, 1)
        elif rest.startswith(EM_DASH) and EM_DASH in rest[len(EM_DASH):]:
            # A bold name alone: who made it is the next clause, when it is a short one.
            clause = rest[len(EM_DASH):].split(EM_DASH, 1)[0]
            if "**" not in clause and len(plain(clause)) <= MAX_PEOPLE:
                people = plain(clause)
        rows.append((ENTRY, bold.strip(), people.strip() if people else None))

    def flush() -> None:
        for bullet in bullets:
            # The bullet's own bold name, and any later sentence that opens with one (a bullet
            # that credits two projects).
            for match in _BOLD.finditer(bullet):
                if match.start() == 0 or bullet[:match.start()].endswith(". "):
                    entry(match, bullet)
        bullets.clear()

    for line in markdown.splitlines():
        if line.startswith("## "):
            flush()
            rows.append((HEADING, plain(line[3:]), None))
        elif line.startswith("- "):
            bullets.append(line[2:].strip())
        elif line.startswith("  ") and bullets and line.strip():
            bullets[-1] += " " + line.strip()
        else:
            if dedication is None:
                found = _DEDICATION.search(plain(line))
                if found:
                    dedication = found.group(1)[0].upper() + found.group(1)[1:]
            if not line.strip() or line.startswith("#"):
                flush()
    flush()
    if dedication is not None:
        rows.append((DEDICATION, dedication, None))
    return rows


def c_string(text: str | None) -> str:
    if text is None:
        return "NULL"
    out = []
    for byte in text.encode("utf-8"):
        char = chr(byte)
        if char in "\\\"":
            out.append("\\" + char)
        elif 0x20 <= byte < 0x7F:
            out.append(char)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def render(rows: list[tuple[str, str, str | None]]) -> str:
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later */",
        "/* Copyright (C) 2026 the Nakagawa Recomp authors */",
        "",
        "/* Generated by tools/gen_credits_table.py from CREDITS.md; do not edit. Run",
        "   python tools/regen_all.py after changing CREDITS.md. */",
        "",
        '#include "launcher_secret.h"',
        "",
        "const LoveAllCredit g_love_all_credits[] = {",
    ]
    for kind, name, people in rows:
        lines.append(f"    {{{kind}, {c_string(name)},")
        lines.append(f"     {c_string(people)}}},")
    lines.append("};")
    lines.append("")
    lines.append("const size_t g_love_all_credit_count =")
    lines.append("    sizeof(g_love_all_credits) / sizeof(g_love_all_credits[0]);")
    return "\n".join(lines) + "\n"


def generate(root: Path = ROOT) -> str:
    return render(parse((root / SOURCE).read_text(encoding="utf-8")))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=ROOT / OUTPUT, help="output file")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when the --out file (by default the committed one) differs "
                             "from a fresh generation")
    args = parser.parse_args(argv)
    text = generate()
    if args.check:
        current = args.out.read_bytes() if args.out.is_file() else b""
        if current != text.encode("utf-8"):
            print(f"gen_credits_table: {OUTPUT.as_posix()} is stale; run python tools/regen_all.py",
                  file=sys.stderr)
            return 1
        print(f"gen_credits_table: {OUTPUT.as_posix()} is current")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
